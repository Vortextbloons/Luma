import { readFile, rm, stat, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const dist = resolve(".remote-dist");
const target = resolve("src-tauri", "src", "phone.html");

let html = await readFile(resolve(dist, "index.html"), "utf8");
const escapeScript = value => value.replace(/<\/script/gi, "<\\/script");
const escapeStyle = value => value.replace(/<\/style/gi, "<\\/style");

for (const tag of [...html.matchAll(/<link\b[^>]*rel="modulepreload"[^>]*>/g)]) {
  html = html.replace(tag[0], "");
}

for (const tag of [...html.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*>/g)]) {
  const href = tag[0].match(/href="([^"]+)"/)?.[1];
  if (!href) continue;
  const css = await readFile(resolve(dist, href.replace(/^\//, "")), "utf8");
  html = html.replace(tag[0], `<style>${escapeStyle(css)}</style>`);
}

for (const tag of [...html.matchAll(/<script\b[^>]*src="([^"]+)"[^>]*><\/script>/g)]) {
  const script = await readFile(resolve(dist, tag[1].replace(/^\//, "")), "utf8");
  html = html.replace(tag[0], `<script type="module">${escapeScript(script)}</script>`);
}

if (/<(?:script|link)\b[^>]*(?:src|href)="\/(?:assets|src)\//.test(html)) {
  throw new Error("Remote build still references external assets");
}

html = html.replace(
  /^<!doctype html>/i,
  "<!doctype html>\n<!-- Generated from remote/ by `npm run build:remote`. Do not edit this file directly. -->",
);

await writeFile(target, html);
await rm(dist, { recursive: true, force: true });

const { size } = await stat(target);
console.log(`Remote built: src-tauri/src/phone.html (${(size / 1024).toFixed(1)} KB)`);
